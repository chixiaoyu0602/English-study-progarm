import { test, expect, type Page } from '@playwright/test'
import { body, fresh, select } from './helpers'

async function lookupSelection(page: Page, word = 'puma') {
  await select(page, word)
  await page.getByRole('button', { name: '查词并加入单词本' }).click()
  await expect(page.getByRole('dialog', { name: word })).toBeVisible()
  await expect(page.getByRole('dialog', { name: word }).locator('.dictionary-meaning')).toBeVisible()
}

test('looks up a selected word, saves its Chinese meaning and sentence, and avoids duplicates', async ({ page }) => {
  await fresh(page)
  await lookupSelection(page)
  const dictionary = page.getByRole('dialog', { name: 'puma' })
  await expect(dictionary).toContainText('美洲狮')
  await expect(dictionary).toContainText('The hunt for the puma began in a small village.')
  await page.getByRole('button', { name: '加入单词本', exact: true }).click()
  await expect(page.getByRole('button', { name: '已在单词本' })).toBeDisabled()
  await page.getByRole('button', { name: '打开单词本' }).click()
  const card = page.getByRole('article', { name: '单词 puma' })
  await expect(card).toContainText('美洲狮')
  await expect(card).toContainText('English study')
  await expect(card).toContainText('The hunt for the puma began in a small village.')
  await page.getByRole('button', { name: '回到原文 puma' }).click()
  await expect(body(page)).toContainText('The hunt for the puma')
  await lookupSelection(page)
  await expect(page.getByRole('button', { name: '已在单词本' })).toBeDisabled()
  await expect(page.locator('.wordbook-count')).toHaveText('1')
})

test('right-click lookup works in pen mode without adding or erasing any annotation', async ({ page }) => {
  await fresh(page, 'The hunt for the puma began in a small village.')
  await select(page, 'The hunt for the puma began in a small village.')
  await page.getByRole('button', { name: '粗记号笔', exact: true }).click()
  const marks = await page.locator('.ink').getAttribute('data-layers')
  const point = await body(page).evaluate(el => {
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT)
    while (walker.nextNode()) {
      const node = walker.currentNode, start = node.textContent!.indexOf('puma')
      if (start < 0) continue
      const range = document.createRange(); range.setStart(node, start); range.setEnd(node, start + 4)
      const rect = range.getBoundingClientRect()
      return { x: rect.left + rect.width / 2, y: rect.top + rect.height / 2 }
    }
    throw new Error('puma not found')
  })
  await page.mouse.click(point.x, point.y, { button: 'right' })
  await expect(page.getByRole('dialog', { name: 'puma' })).toContainText('美洲狮')
  await expect(page.locator('.ink')).toHaveCount(1)
  await expect(page.locator('.ink')).toHaveAttribute('data-layers', marks!)
  await page.getByRole('button', { name: '加入单词本', exact: true }).click()
  await expect(page.locator('.ink')).toHaveAttribute('data-layers', marks!)
})

test('supports Ctrl D and includes the base meaning for irregular words', async ({ page }) => {
  await fresh(page, 'The puma escaped. It ran away when she saw it.')
  await select(page, 'ran')
  await page.keyboard.press('Control+d')
  const dialog = page.getByRole('dialog', { name: 'ran' })
  await expect(dialog).toContainText('原形 run')
  await expect(dialog).toContainText('跑')
  await expect(dialog.locator('.dictionary-source')).toHaveText('文章中的原句It ran away when she saw it.')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})

test('persists words after reload and searches, looks up, and removes entries in the wordbook', async ({ page }) => {
  await fresh(page)
  await lookupSelection(page)
  await page.getByRole('button', { name: '加入单词本', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存到本机' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '打开单词本' }).click()
  await expect(page.getByRole('article', { name: '单词 puma' })).toContainText('美洲狮')
  const search = page.getByRole('textbox', { name: '搜索单词或中文释义' })
  await search.fill('美洲狮')
  await expect(page.locator('.word-card')).toHaveCount(1)
  await search.fill('unfamiliar')
  await search.press('Enter')
  await expect(page.getByRole('dialog', { name: 'unfamiliar' })).toContainText('不熟悉')
  await page.getByRole('button', { name: '加入单词本', exact: true }).click()
  await page.getByRole('button', { name: '关闭查词' }).click()
  await expect(page.getByRole('article', { name: '单词 unfamiliar' })).toBeVisible()
  await search.fill('')
  await expect(page.locator('.word-card')).toHaveCount(2)
  await page.getByRole('button', { name: '移出单词本 puma' }).click()
  await expect(page.locator('.word-card')).toHaveCount(1)
})

test('backup restores vocabulary, merges duplicates and remaps article links', async ({ page }) => {
  await fresh(page)
  await lookupSelection(page)
  await page.getByRole('button', { name: '加入单词本', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存到本机' })).toBeVisible()
  const originalId = await page.evaluate(() => JSON.parse(localStorage.getItem('marknote.notebook.v1')!).activeId)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出备份' }).click()
  const path = await (await downloadPromise).path()
  await page.getByRole('button', { name: '打开单词本' }).click()
  await page.getByRole('button', { name: '移出单词本 puma' }).click()
  await page.locator('input[type=file]').setInputFiles(path!)
  await page.getByRole('button', { name: '打开单词本' }).click()
  await expect(page.getByRole('article', { name: '单词 puma' })).toContainText('美洲狮')
  await expect(page.locator('.wordbook-count')).toHaveText('1')
  await page.getByRole('button', { name: '回到原文 puma' }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存到本机' })).toBeVisible()
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('marknote.notebook.v1')!))
  expect(restored.vocabulary[0].source.noteId).not.toBe(originalId)
  expect(restored.notes.some((note: { id: string }) => note.id === restored.vocabulary[0].source.noteId)).toBe(true)
  await page.locator('input[type=file]').setInputFiles(path!)
  await expect(page.locator('.wordbook-count')).toHaveText('1')
})

