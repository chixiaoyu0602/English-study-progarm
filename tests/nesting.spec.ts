test('keyboard opening and shortcuts stay inside the panel and the close button traps focus', async ({ page }) => {
  await primary(page)
  await page.getByRole('button', { name: '打开片段分析' }).focus()
  await page.keyboard.press('Enter')
  await expect(panel(page)).toBeVisible()
  await panel(page).getByRole('textbox', { name: '片段文字' }).focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Control+Shift+h')
  await expect(panel(page).locator('[data-detail-ink]')).toHaveText(clause)
  await page.keyboard.press('Control+z')
  await expect(panel(page).locator('[data-detail-ink]')).toHaveCount(0)
  await page.getByRole('button', { name: '关闭片段分析' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(panel(page).getByRole('textbox', { name: '片段文字' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel(page)).toHaveCount(0)
  await expect(body(page)).toHaveText(clause)
})

test('legacy nesting moves inside the panel and both light and dark views stay free of rails', async ({ page }) => {
  await fresh(page)
  const yellow = { id: 'outer', color: '#f3cf62', width: 'wide' }, red = { id: 'inner', color: '#f09a91', width: 'wide' }
  const marked = (text: string, layers: object[]) => ({ type: 'text', text, marks: [{ type: 'ink', attrs: { color: '#f3cf62', width: 'wide', layers } }] })
  const legacy = { version: 3, notes: [{ id: 'old', title: '旧版片段', createdAt: 1, updatedAt: 1, content: { type: 'doc', content: [{ type: 'paragraph', content: [marked('where ', [yellow]), marked('saw', [red, yellow]), marked(' her', [yellow])] }] } }], activeId: 'old', vocabulary: [], theme: 'dark', color: '#f3cf62', pen: 'wide', customColors: [], fontSize: 20 }
  await page.locator('input[type=file]').setInputFiles({ name: 'old.marknote', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy)) })
  await page.getByRole('button', { name: '切换到夜间模式' }).click()
  await expect(page.locator('.ink-framed, .ink-start, .ink-end')).toHaveCount(0)
  await openAnalysis(page)
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
  await expect(panel(page).locator('.ink-surface')).toHaveCSS('box-shadow', 'none')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '切换到日间模式' }).click()
  await openAnalysis(page)
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
})

