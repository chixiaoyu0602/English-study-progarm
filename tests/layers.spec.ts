test('legacy backups keep original highlights and can receive and persist new layers', async ({ page }) => {
  await fresh(page)
  const old = { version: 1, notes: [{ id: 'old-note', title: '旧版笔记', createdAt: 1, updatedAt: 1, content: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'legacy text', marks: [{ type: 'ink', attrs: { color: '#f3cf62', width: 'wide' } }] }] }] } }], activeId: 'old-note', theme: 'light', color: '#f3cf62', pen: 'wide', customColors: [], fontSize: 20 }
  await page.locator('input[type=file]').setInputFiles({ name: 'legacy.marknote', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(old)) })
  await expect(page.locator('.ink')).toHaveAttribute('data-layer-count', '1')
  await page.getByRole('button', { name: '珊瑚红', exact: true }).click()
  await select(page, 'legacy')
  await page.getByRole('button', { name: '粗记号笔', exact: true }).click()
  await expect(page.locator('.ink-layered')).toHaveAttribute('data-layer-count', '2')
  await expect(page.getByRole('status').filter({ hasText: '已保存到本机' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.ink-layered')).toHaveText('legacy')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('marknote.notebook.v1')!).version)).toBe(3)
})

test('layer limits reject the whole stroke and repeating a color does not consume a layer', async ({ page }) => {
  await fresh(page, 'puma')
  const colors = ['麦芽黄', '珊瑚红', '草木绿', '晴空蓝', '丁香紫', '麦芽黄', '珊瑚红', '草木绿']
  for (const color of colors) {
    await page.getByRole('button', { name: color, exact: true }).click()
    await select(page, 'puma')
    await page.getByRole('button', { name: '粗记号笔', exact: true }).click()
  }
  await expect(page.locator('.ink')).toHaveAttribute('data-layer-count', '8')
  await select(page, 'puma')
  await page.getByRole('button', { name: '粗记号笔', exact: true }).click()
  await expect(page.locator('.ink')).toHaveAttribute('data-layer-count', '8')
  await select(page, 'puma')
  await page.getByRole('button', { name: '晴空蓝', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '最多叠加 8 层' })).toBeVisible()
  await expect(page.locator('.ink')).toHaveAttribute('data-layer-count', '8')
  await expect(page.locator('.ink')).toHaveAttribute('data-color', '#a2cf95')
})
