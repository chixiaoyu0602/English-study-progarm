import { test, expect } from '@playwright/test'
import { body, fresh, select, openAnalysis, panel, selectDetail, paintDetail } from './helpers'

const clause = "where a woman picking blackberries saw 'a large cat' only five yards away from her"
async function primary(page: import('@playwright/test').Page, text = clause) {
  await fresh(page, text)
  if (text.includes('\n')) {
    await body(page).press('Control+a')
    await expect(page.locator('.tool-hint')).toContainText('选择一支记号笔')
  } else await select(page, text)
  await page.getByRole('button', { name: '粗记号笔', exact: true }).click()
}

test('a coloured block opens as plain source text; detail colours never appear in the article or open a third level', async ({ page }) => {
  await primary(page)
  await openAnalysis(page)
  await expect(panel(page).getByRole('textbox', { name: '片段文字' })).toHaveText(clause)
  await expect(panel(page).locator('[data-detail-ink]')).toHaveCount(0)
  await paintDetail(page, 'saw')
  await paintDetail(page, 'only five yards away from her', '麦芽黄')
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
  await expect(panel(page).locator('[data-color="#f3cf62"]')).toHaveText('only five yards away from her')
  await panel(page).locator('[data-color="#f09a91"]').click()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(panel(page).locator('[data-analysis-id]')).toHaveCount(0)
  await page.getByRole('button', { name: '关闭片段分析' }).click()
  await expect(page.locator('.tiptap [data-visible-color="#f09a91"]')).toHaveCount(0)
  const colors = await page.locator('.tiptap [data-visible-color]').evaluateAll(es => es.map(el => el.getAttribute('data-visible-color')))
  expect(new Set(colors)).toEqual(new Set(['#f3cf62']))
  await openAnalysis(page)
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
})

test('analysis persists across reload, export and import, including same-colour details', async ({ page }) => {
  await primary(page)
  await openAnalysis(page)
  await paintDetail(page, 'a woman', '麦芽黄')
  await paintDetail(page, 'saw')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('status').filter({ hasText: '已保存到本机' })).toBeVisible()
  await page.reload()
  await openAnalysis(page)
  await expect(panel(page).locator('[data-color="#f3cf62"]')).toHaveText('a woman')
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
  await page.keyboard.press('Escape')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出备份' }).click()
  await page.locator('input[type=file]').setInputFiles((await (await download).path())!)
  await openAnalysis(page)
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('saw')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('marknote.notebook.v1')!).version)).toBe(4)
})

test('detail recolouring, fine pen, erase and undo affect only the second view', async ({ page }) => {
  await primary(page)
  await openAnalysis(page)
  await paintDetail(page, 'picking blackberries')
  await paintDetail(page, 'blackberries', '晴空蓝', '细记号笔')
  await expect(panel(page).locator('[data-color="#94c9e9"]')).toHaveText('blackberries')
  await selectDetail(page, 'blackberries')
  await panel(page).getByRole('button', { name: '橡皮擦', exact: true }).click()
  await expect(panel(page).locator('[data-color="#f09a91"]')).toHaveText('picking blackberries')
  await panel(page).getByRole('button', { name: '撤销', exact: true }).click()
  await expect(panel(page).locator('[data-color="#94c9e9"]')).toHaveText('blackberries')
  await panel(page).getByRole('button', { name: '重做', exact: true }).click()
  await paintDetail(page, 'blackberries', '草木绿')
  await expect(panel(page).locator('[data-color="#a2cf95"]')).toHaveText('blackberries')
  await selectDetail(page, 'blackberries')
  await panel(page).getByRole('button', { name: '橡皮擦', exact: true }).click()
  await expect(panel(page).locator('[data-detail-ink]').filter({ hasText: /^blackberries$/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(body(page)).toHaveText(clause)
  expect(await page.locator('.tiptap [data-visible-color]').evaluateAll(es => es.every(el => el.getAttribute('data-visible-color') === '#f3cf62'))).toBe(true)
})

